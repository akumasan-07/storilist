export function getMediaById(id: string): MediaItem | undefined {
  const cleanId = id.toLowerCase().trim();
  return SAMPLE_MEDIA_ITEMS.find(
    (item) => item.id.toLowerCase() === cleanId
  );
}

export function getRelatedMedia(
  category: string,
  excludeId: string,
  limit: number = 4
): MediaItem[] {
  return SAMPLE_MEDIA_ITEMS.filter(
    (item) => item.category === category && item.id !== excludeId
  ).slice(0, limit);
}
